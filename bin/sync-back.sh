#!/usr/bin/env bash
#
# AI Setup — Sync Back
#
# Copies AI config changes from an active project back into the ai-setup repo,
# creates a feature branch, commits, and opens a PR against develop.
# Never pushes to a protected branch.
#
# Usage:
#   ./bin/sync-back.sh /path/to/active/project
#
# Domain is auto-detected from the project path against config/domains.conf.
# Only files listed for that domain are synced.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh
. "$SCRIPT_DIR/../lib/common.sh"

if [ $# -lt 1 ]; then
    log_error "Usage: $(basename "$0") <project_path>"
fi

PROJECT_PATH="$1"
[ -d "$PROJECT_PATH" ] || log_error "Project path not found: $PROJECT_PATH"

domain=$(detect_domain "$PROJECT_PATH") || log_error "Could not determine domain for $PROJECT_PATH"
ws=$(get_domain_workspace "$domain")
log_info "Detected domain: $domain (→ $ws)"

# ── Resolve actual symlink targets so we copy back into the right files ──
# A file in the project may be a symlink into ai-setup; readlink -f resolves
# the canonical destination so we don't accidentally overwrite the symlink
# with itself.
copy_file() {
    local src_in_project="$1"
    local dest_in_repo="$2"

    if [ ! -e "$src_in_project" ]; then
        log_warn "skip (not in project): $(basename "$src_in_project")"
        return
    fi

    # If src is a symlink that already points at dest, nothing to do.
    if [ -L "$src_in_project" ]; then
        local target
        target=$(readlink "$src_in_project")
        case "$target" in
            "$dest_in_repo") log_info "skip (symlink already up to date): $(basename "$src_in_project")"; return ;;
        esac
    fi

    if cmp -s "$src_in_project" "$dest_in_repo" 2>/dev/null; then
        log_info "skip (no diff): $(basename "$src_in_project")"
        return
    fi

    cp "$src_in_project" "$dest_in_repo"
    log_ok "synced: $(basename "$src_in_project")"
}

# ── Work in the repo so git commands target the right tree ──
cd "$REPO_ROOT"

# ── Sync each managed file ──
# get_domain_files returns the repo-side (dest) path. get_domain_file_src
# resolves the corresponding project-side filename (handles source>dest mappings).
synced_any=0
while IFS= read -r f; do
    [ -n "$f" ] || continue
    proj_f=$(get_domain_file_src "$domain" "$f")
    src="$PROJECT_PATH/$proj_f"
    dst="$REPO_ROOT/$ws/$f"
    if [ -e "$src" ] && ! cmp -s "$src" "$dst" 2>/dev/null; then
        copy_file "$src" "$dst"
        synced_any=1
    fi
done < <(get_domain_files "$domain")

if [ "$synced_any" -eq 0 ]; then
    log_info "Nothing to sync — all files match."
    exit 0
fi

# ── Git flow: branch, commit, PR ──
require git "brew install git"

current_branch=$(git rev-parse --abbrev-ref HEAD)
date_tag=$(date '+%Y-%m-%d')
new_branch="ai-config/sync-${domain}-${date_tag}"

# If branch exists, append a counter
suffix=1
while git show-ref --quiet --verify "refs/heads/$new_branch"; do
    suffix=$((suffix + 1))
    new_branch="ai-config/sync-${domain}-${date_tag}-$suffix"
done

log_info "Creating branch: $new_branch"
git checkout -b "$new_branch"

git add "$ws"
project_name=$(basename "$PROJECT_PATH")
git commit -m "sync: $domain config from $project_name"

log_info "Pushing branch..."
git push -u origin "$new_branch"

# ── PR creation: detect gh vs glab ──
pr_tool=""
if command -v gh >/dev/null 2>&1; then
    log_info "Opening PR via gh..."
    gh pr create --base develop --head "$new_branch" \
        --title "ai-config: sync $domain from $project_name" \
        --body "Auto-generated by \`just sync\`. Synced files in \`$ws/\` from \`$project_name\`."
    pr_tool="gh"
elif command -v glab >/dev/null 2>&1; then
    log_info "Opening MR via glab..."
    glab mr create --target-branch develop --source-branch "$new_branch" \
        --title "ai-config: sync $domain from $project_name" \
        --description "Auto-generated by \`just sync\`. Synced files in \`$ws/\` from \`$project_name\`." \
        --fill --yes
    pr_tool="glab"
else
    log_warn "Neither 'gh' nor 'glab' installed. Open the PR manually:"
    printf '  Branch: %s\n  Base: develop\n' "$new_branch"
fi

# ── Post full benchmark as a comment on the new PR/MR ──
# Refresh the synced domain's score first so the comment reflects this PR's state.
# Skip if AI_SETUP_SKIP_EVAL is set or Claude CLI is unavailable (e.g. CI).
if [ -n "$pr_tool" ] && [ "${AI_SETUP_SKIP_EVAL:-0}" != "1" ] && command -v claude >/dev/null 2>&1; then
    log_info "Re-scoring $domain to refresh benchmark..."
    "$HARNESS_ROOT/evals/run-eval.sh" "$domain" || log_warn "Eval failed; comment will use last-known scores."

    comment_body=$(mktemp)
    {
        printf '## Benchmark — full domain scores\n\n'
        printf 'Refreshed after this PR. See `evals/results/` for full findings per domain.\n\n'
        printf '```\n'
        "$HARNESS_ROOT/benchmarks/report.sh"
        printf '```\n'
    } >"$comment_body"

    case "$pr_tool" in
        gh)
            gh pr comment "$new_branch" --body-file "$comment_body" \
                || log_warn "Could not post PR comment."
            ;;
        glab)
            glab mr note "$new_branch" --message "$(cat "$comment_body")" \
                || log_warn "Could not post MR note."
            ;;
    esac
    rm -f "$comment_body"
else
    [ -n "$pr_tool" ] && log_info "Skipping benchmark comment (eval disabled or claude CLI missing)."
fi

log_ok "Returning to $current_branch"
git checkout "$current_branch"
